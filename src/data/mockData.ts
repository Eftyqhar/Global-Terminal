// Realistic Candlestick generator for any given base price and volatility
export function generateCandles(basePrice: number, count: number = 40, volatility: number = 0.015): Candle[] {
  const candles: Candle[] = [];
  let currentPrice = basePrice * (1 - volatility * (count / 2) * 0.4);
  const now = Date.now();
  const stepMs = 3600 * 1000 * 4; // 4 hour candles

  for (let i = count; i >= 0; i--) {
    const timestamp = now - i * stepMs;
    const date = new Date(timestamp);
    const timeStr = `${date.getMonth() + 1}/${date.getDate()} ${date.getHours().toString().padStart(2, '0')}:00`;

    const change = (Math.random() - 0.48) * volatility * currentPrice;
    const open = currentPrice;
    const close = +(open + change).toFixed(2);
    const high = +(Math.max(open, close) + Math.random() * volatility * currentPrice * 0.7).toFixed(2);
    const low = +(Math.min(open, close) - Math.random() * volatility * currentPrice * 0.7).toFixed(2);
    const volume = Math.floor(10000 + Math.random() * 80000);

    currentPrice = close;
    candles.push({
      timestamp,
      timeStr,
      open,
      high,
      low,
      close,
      volume,
    });
  }

  // Calculate technical indicators: SMA20, SMA50, RSI
  for (let i = 0; i < candles.length; i++) {
    if (i >= 19) {
      const sum20 = candles.slice(i - 19, i + 1).reduce((acc, c) => acc + c.close, 0);
      candles[i].sma20 = +(sum20 / 20).toFixed(2);
    }
    if (i >= 49) {
      const sum50 = candles.slice(i - 49, i + 1).reduce((acc, c) => acc + c.close, 0);
      candles[i].sma50 = +(sum50 / 50).toFixed(2);
    }

    // RSI (14)
    if (i >= 14) {
      let gains = 0;
      let losses = 0;
      for (let j = i - 13; j <= i; j++) {
        const diff = candles[j].close - candles[j - 1].close;
        if (diff >= 0) gains += diff;
        else losses += Math.abs(diff);
      }
      const avgGain = gains / 14;
      const avgLoss = losses / 14;
      if (avgLoss === 0) {
        candles[i].rsi = 100;
      } else {
        const rs = avgGain / avgLoss;
        candles[i].rsi = +(100 - (100 / (1 + rs))).toFixed(1);
      }
    } else {
      candles[i].rsi = 50.0;
    }
  }

  return candles;
}
